export function translate(language, key, values = {}) {
  return (translations[language][key] ?? translations.en[key] ?? key).replace(
    /\{(\w+)\}/g,
    (_, name) => values[name] ?? '',
  )
}

export const localeFor = (language) => (language === 'ar' ? 'ar-SA-u-ca-gregory-nu-arab' : 'en-GB')
export const formatNumber = (value, language) =>
  new Intl.NumberFormat(localeFor(language), { useGrouping: false }).format(value)

export function initialLanguage() {
  try {
    return localStorage.getItem('fleetline-language') === 'ar' ? 'ar' : 'en'
  } catch {
    return 'en'
  }
}
